import torch
import torch.nn as nn


class ROP_Predictor(nn.Module):
    def __init__(self):
        # 1. ОБЯЗАТЕЛЬНО: Инициализируем родительский класс nn.Module
        # Без этой строчки PyTorch выдаст ошибку
        super().__init__()

        # Создаем "склад" наших слоев
        # Вход: 4 фичи (WOB, RPM, Flow Rate, Torque) -> выход 64 нейрона
        self.fc1 = nn.Linear(4, 64)

        # Функция активации (добавляет нелинейность, чтобы сеть могла учить сложные вещи)
        self.relu = nn.ReLU()

        # Скрытый слой: 64 нейрона -> 32 нейрона
        self.fc2 = nn.Linear(64, 32)

        # Выходной слой: 32 нейрона -> 1 число (наш ROP)
        self.fc3 = nn.Linear(32, 1)

    def forward(self, x):
        # 2. КОНВЕЙЕР: Пропускаем входные данные 'x' через наши слои по очереди

        x = self.fc1(x)    # Пропускаем через первый слой
        x = self.relu(x)   # Применяем активацию

        x = self.fc2(x)    # Пропускаем через второй слой
        # Снова применяем активацию (между скрытыми слоями это стандарт)
        x = self.relu(x)

        x = self.fc3(x)    # Пропускаем через финальный слой

        # 3. Возвращаем готовое предсказание
        return x
